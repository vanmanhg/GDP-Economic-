import { EconomicEntity, CopilotChatMessage, HistoricalMetricKey } from '../types';
import { calculateMacroConfidence } from './macroConfidenceCalculator';
import { HISTORICAL_METRIC_SPECS } from '../data/historicalExtendedData';

/**
 * Generates a structured Markdown intelligence dossier for the current Copilot chat history.
 */
export function generateChatHistoryMarkdown(
  messages: CopilotChatMessage[],
  entityA: EconomicEntity,
  entityB: EconomicEntity
): string {
  const exportDate = new Date();
  const dateFormatted = exportDate.toLocaleString('en-US', {
    dateStyle: 'full',
    timeStyle: 'medium',
  });

  const latestAnalysis = [...messages].reverse().find((m) => m.analysisResult)?.analysisResult;
  const confidenceA = calculateMacroConfidence(entityA, entityB, latestAnalysis);
  const confidenceB = calculateMacroConfidence(entityB, entityA, latestAnalysis);

  const lines: string[] = [];

  // Header Section
  lines.push(`# Macroeconomic Intelligence Dossier: ${entityA.name} vs ${entityB.name}`);
  lines.push('');
  lines.push(`> **Generated by:** Macro Analyst Copilot · AI Studio Macroeconomics Platform`);
  lines.push(`> **Exported:** ${dateFormatted}`);
  lines.push(`> **Total Conversation Exchanges:** ${messages.length}`);
  lines.push(`> **Active Comparison:** ${entityA.flag} **${entityA.name}** (${entityA.shortName}) vs ${entityB.flag} **${entityB.name}** (${entityB.shortName})`);
  lines.push('');

  // Macro Confidence Score Card
  lines.push('---');
  lines.push('## 1. Macroeconomic Confidence & Comparative Outlook');
  lines.push('');
  lines.push('| Entity | Confidence Score | Stance / Sentiment | Primary Macro Strength | Key Vulnerability / Risk |');
  lines.push('| :--- | :---: | :--- | :--- | :--- |');
  lines.push(
    `| ${entityA.flag} **${entityA.shortName}** | **${confidenceA.score}/100** | ${confidenceA.sentiment} | ${confidenceA.primaryStrength} | ${confidenceA.primaryRisk} |`
  );
  lines.push(
    `| ${entityB.flag} **${entityB.shortName}** | **${confidenceB.score}/100** | ${confidenceB.sentiment} | ${confidenceB.primaryStrength} | ${confidenceB.primaryRisk} |`
  );
  lines.push('');
  lines.push(`- **${entityA.shortName} Outlook Thesis:** ${confidenceA.summaryTakeaway}`);
  lines.push(`- **${entityB.shortName} Outlook Thesis:** ${confidenceB.summaryTakeaway}`);
  lines.push('');

  // Conversation Chronology
  lines.push('---');
  lines.push('## 2. Conversation & Scenario Intelligence Briefings');
  lines.push('');

  if (messages.length === 0) {
    lines.push('_No conversation exchanges recorded in this session._');
    lines.push('');
  } else {
    messages.forEach((msg, idx) => {
      lines.push(`### Exchange #${idx + 1}: ${msg.sender === 'user' ? '👤 User Inquiry' : '🤖 AI Analyst Synthesis'}`);
      lines.push(`- **Scenario / Title:** ${msg.scenarioTitle || (msg.sender === 'user' ? 'Custom Macro Query' : 'Comparative Synthesis')}`);
      lines.push(`- **Timestamp:** ${msg.timestamp}`);

      if (msg.sender === 'user') {
        lines.push('');
        lines.push('**Inquiry Text:**');
        lines.push(`> ${msg.text}`);
        lines.push('');
      } else {
        const res = msg.analysisResult;
        lines.push(`- **Reasoning Source:** ${res?.source === 'gemini_3_8_flash' ? 'Gemini 3.8 Flash (Live Reasoning)' : 'Macroeconomic Reference Engine'}`);

        if (msg.discussedMetrics && msg.discussedMetrics.length > 0) {
          const metricNames = msg.discussedMetrics
            .map((k: HistoricalMetricKey) => HISTORICAL_METRIC_SPECS[k]?.label || k)
            .join(', ');
          lines.push(`- **Discussed Multi-Year Indicators:** ${metricNames}`);
        }

        lines.push('');

        if (res) {
          // Executive Thesis
          lines.push('#### Executive Thesis');
          res.executiveThesis.forEach((t) => {
            lines.push(`- ${t}`);
          });
          lines.push('');

          // Key Transmission Mechanisms
          if (res.keyTransmissionMechanisms && res.keyTransmissionMechanisms.length > 0) {
            lines.push('#### Key Transmission Mechanisms');
            lines.push('');
            lines.push(`| Transmission Channel | ${entityA.shortName} Shock Response | ${entityB.shortName} Shock Response | Divergence Factor |`);
            lines.push('| :--- | :--- | :--- | :--- |');
            res.keyTransmissionMechanisms.forEach((m) => {
              const cleanA = m.entityAResponse.replace(/\|/g, '\\|');
              const cleanB = m.entityBResponse.replace(/\|/g, '\\|');
              const cleanDiv = m.divergenceFactor.replace(/\|/g, '\\|');
              lines.push(`| **${m.title}** | ${cleanA} | ${cleanB} | ${cleanDiv} |`);
            });
            lines.push('');
          }

          // Asymmetric Vulnerabilities
          if (res.asymmetricVulnerabilities) {
            lines.push('#### Asymmetric Vulnerabilities');
            lines.push(`- **${entityA.shortName}:** ${res.asymmetricVulnerabilities.entityA.join('; ')}`);
            lines.push(`- **${entityB.shortName}:** ${res.asymmetricVulnerabilities.entityB.join('; ')}`);
            lines.push('');
          }

          // Indicator Projections (if present)
          if (res.projections && res.projections.length > 0) {
            lines.push('#### Indicator Projections');
            lines.push('');
            lines.push(`| Indicator | ${entityA.shortName} Baseline -> Projected | ${entityB.shortName} Baseline -> Projected | Divergence Takeaway |`);
            lines.push('| :--- | :--- | :--- | :--- |');
            res.projections.forEach((p) => {
              const projA = `${p.entityAProjection.baseline} -> ${p.entityAProjection.projectedShift} (${p.entityAProjection.deltaBps})`;
              const projB = `${p.entityBProjection.baseline} -> ${p.entityBProjection.projectedShift} (${p.entityBProjection.deltaBps})`;
              lines.push(`| **${p.indicator}** | ${projA} | ${projB} | ${p.divergenceTakeaway} |`);
            });
            lines.push('');
          }

          // Policy Recommendations
          if (res.policyRecommendations) {
            lines.push('#### Policy Recommendations');
            lines.push(`- **${entityA.flag} ${entityA.shortName}:** ${res.policyRecommendations.entityA}`);
            lines.push(`- **${entityB.flag} ${entityB.shortName}:** ${res.policyRecommendations.entityB}`);
            lines.push('');
          }
        } else if (msg.text) {
          lines.push('**Synthesis Summary:**');
          lines.push(msg.text);
          lines.push('');
        }
      }

      lines.push('---');
    });
  }

  // Footer Disclaimer
  lines.push('');
  lines.push('### Disclaimer & Methodology');
  lines.push('This document was compiled from conversational session state within the Macro Analyst Copilot. Data points and scenario assessments are for research, policy analysis, and strategic intelligence exploration.');
  lines.push('');

  return lines.join('\n');
}

/**
 * Generates a structured JSON representation of the chat history and comparative analysis.
 */
export function generateChatHistoryJson(
  messages: CopilotChatMessage[],
  entityA: EconomicEntity,
  entityB: EconomicEntity
): object {
  const exportDate = new Date();
  const latestAnalysis = [...messages].reverse().find((m) => m.analysisResult)?.analysisResult;
  const confidenceA = calculateMacroConfidence(entityA, entityB, latestAnalysis);
  const confidenceB = calculateMacroConfidence(entityB, entityA, latestAnalysis);

  return {
    exportMetadata: {
      title: 'Macro Analyst Copilot Chat History & Comparative Intelligence Export',
      schemaVersion: '1.0.0',
      exportedAt: exportDate.toISOString(),
      localeTimestamp: exportDate.toLocaleString(),
      application: 'Macroeconomic Indicator & Intelligence Platform',
      comparisonSession: {
        entityA: {
          id: entityA.id,
          name: entityA.name,
          shortName: entityA.shortName,
          flag: entityA.flag,
          type: entityA.type,
          nominalGdp: entityA.nominalGdp,
          gdpGrowthRate: entityA.gdpGrowthRate,
          inflationRate: entityA.inflationRate,
          unemploymentRate: entityA.unemploymentRate,
          publicDebtToGdp: entityA.publicDebtToGdp,
        },
        entityB: {
          id: entityB.id,
          name: entityB.name,
          shortName: entityB.shortName,
          flag: entityB.flag,
          type: entityB.type,
          nominalGdp: entityB.nominalGdp,
          gdpGrowthRate: entityB.gdpGrowthRate,
          inflationRate: entityB.inflationRate,
          unemploymentRate: entityB.unemploymentRate,
          publicDebtToGdp: entityB.publicDebtToGdp,
        },
      },
      macroConfidenceOverview: {
        entityA: confidenceA,
        entityB: confidenceB,
      },
      messageCount: messages.length,
      userInquiryCount: messages.filter((m) => m.sender === 'user').length,
      assistantSynthesisCount: messages.filter((m) => m.sender === 'assistant').length,
    },
    messages: messages.map((m) => ({
      id: m.id,
      sender: m.sender,
      timestamp: m.timestamp,
      scenarioTitle: m.scenarioTitle || (m.sender === 'user' ? 'Custom Macro Inquiry' : 'Comparative Synthesis'),
      text: m.text,
      discussedMetrics: m.discussedMetrics || [],
      analysisResult: m.analysisResult || null,
    })),
  };
}

/**
 * Triggers a native file download in the browser.
 */
export function triggerFileDownload(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/**
 * Helper to download the chat history in the requested format (Markdown or JSON).
 */
export function downloadChatHistory(
  messages: CopilotChatMessage[],
  entityA: EconomicEntity,
  entityB: EconomicEntity,
  format: 'markdown' | 'json'
): string {
  const dateStr = new Date().toISOString().slice(0, 10);
  const cleanA = entityA.shortName.toLowerCase().replace(/[^a-z0-9]/g, '-');
  const cleanB = entityB.shortName.toLowerCase().replace(/[^a-z0-9]/g, '-');

  if (format === 'markdown') {
    const filename = `macro-copilot-analysis-${cleanA}-vs-${cleanB}-${dateStr}.md`;
    const content = generateChatHistoryMarkdown(messages, entityA, entityB);
    triggerFileDownload(filename, content, 'text/markdown');
    return filename;
  } else {
    const filename = `macro-copilot-analysis-${cleanA}-vs-${cleanB}-${dateStr}.json`;
    const contentObj = generateChatHistoryJson(messages, entityA, entityB);
    const content = JSON.stringify(contentObj, null, 2);
    triggerFileDownload(filename, content, 'application/json');
    return filename;
  }
}
