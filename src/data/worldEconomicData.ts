/**
 * Returns baseline estimation for any country not explicitly configured,
 * ensuring seamless 100% choropleth coverage across all 177 TopoJSON polygons.
 */
export function getCountryEconomicData(id?: string, name?: string): WorldCountryEconomicData {
  if (id && WORLD_COUNTRIES_DATA[id]) {
    return WORLD_COUNTRIES_DATA[id];
  }

  // Fallback estimates calibrated by geography & natural regional benchmarks
  const cleanName = name || `Country ${id || 'Unknown'}`;
  const isIslandOrMicro = ['Fiji', 'Vanuatu', 'Solomon Is.', 'New Caledonia', 'Bahamas', 'Belize'].some((n) => cleanName.includes(n));
  const isEurope = ['Estonia', 'Latvia', 'Lithuania', 'Slovakia', 'Slovenia', 'Croatia', 'Bulgaria', 'Romania', 'Serbia', 'Albania', 'Bosnia', 'Montenegro', 'North Macedonia', 'Moldova', 'Belarus', 'Iceland', 'Luxembourg', 'Cyprus', 'Kosovo'].some((n) => cleanName.includes(n));
  const isOil = ['Oman', 'Iraq', 'Libya', 'Turkmenistan', 'Gabon', 'Eq. Guinea'].some((n) => cleanName.includes(n));
  const isAfricaLow = ['Sudan', 'Chad', 'Niger', 'Mali', 'Burkina Faso', 'Somalia', 'Somaliland', 'Central African Rep.', 'Dem. Rep. Congo', 'Congo', 'Burundi', 'Rwanda', 'Malawi', 'Mozambique', 'Zambia', 'Zimbabwe', 'Madagascar', 'Sierra Leone', 'Liberia', 'Guinea', 'Benin', 'Togo'].some((n) => cleanName.includes(n));

  let perCapita = 4500;
  let gdp = 45;
  let pop = 10;
  let continent: WorldCountryEconomicData['continent'] = 'Africa';
  let incomeGroup: WorldCountryEconomicData['incomeGroup'] = 'Lower Middle';

  if (isEurope) {
    perCapita = 21000;
    gdp = 120;
    pop = 5.5;
    continent = 'Europe';
    incomeGroup = 'High Income';
  } else if (isOil) {
    perCapita = 22000;
    gdp = 110;
    pop = 5;
    continent = 'Middle East';
    incomeGroup = 'High Income';
  } else if (isAfricaLow) {
    perCapita = 1200;
    gdp = 25;
    pop = 22;
    continent = 'Africa';
    incomeGroup = 'Low Income';
  } else if (isIslandOrMicro) {
    perCapita = 9500;
    gdp = 12;
    pop = 1.2;
    continent = 'Asia-Pacific';
    incomeGroup = 'Upper Middle';
  }

  const resolvedId = id || (name ? `geo-${name.toLowerCase().replace(/[^a-z0-9]/g, '-')}` : `geo-${Math.random().toString(36).slice(2, 7)}`);

  return {
    id: resolvedId,
    iso3: cleanName.slice(0, 3).toUpperCase(),
    name: cleanName,
    commonName: cleanName,
    flag: '🌐',
    continent,
    gdpPerCapitaNominal: perCapita,
    gdpPerCapitaPpp: Math.round(perCapita * 1.7),
    nominalGdp: gdp,
    gdpPpp: Math.round(gdp * 1.7),
    population: pop,
    gdpGrowthRate: 3.5,
    inflationRate: 4.2,
    unemploymentRate: 5.8,
    publicDebtToGdp: 52.0,
    hdi: perCapita > 15000 ? 0.85 : 0.65,
    incomeGroup,
    keyIndustries: ['Agriculture & Resources', 'Trade & Services', 'Manufacturing'],
    summaryNote: `${cleanName} macroeconomic indicators based on regional developmental brackets.`,
  };
}

